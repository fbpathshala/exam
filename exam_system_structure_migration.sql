-- ============================================================
-- ৫) Folder / Set helper RPCs
-- ============================================================
drop function if exists public.create_question_bank_folder(text,text);
create or replace function public.create_question_bank_folder(
  p_sub_category text,
  p_folder_name text
)
returns public.question_bank_folders
language plpgsql security definer set search_path=public
as $$
declare r public.question_bank_folders;
begin
  if auth.uid() is null then raise exception 'Admin login required'; end if;
  insert into public.question_bank_folders(sub_category,folder_name)
  values(trim(p_sub_category),trim(p_folder_name))
  on conflict(sub_category,folder_name) do update set folder_name=excluded.folder_name
  returning * into r;
  return r;
end;
$$;

drop function if exists public.create_question_bank_set(bigint,text);
create or replace function public.create_question_bank_set(
  p_folder_id bigint,
  p_set_name text
)
returns public.question_bank_sets
language plpgsql security definer set search_path=public
as $$
declare r public.question_bank_sets;
begin
  if auth.uid() is null then raise exception 'Admin login required'; end if;
  insert into public.question_bank_sets(folder_id,set_name)
  values(p_folder_id,trim(p_set_name))
  on conflict(folder_id,set_name) do update set set_name=excluded.set_name
  returning * into r;
  return r;
end;
$$;

grant execute on function public.create_question_bank_folder(text,text) to authenticated;
grant execute on function public.create_question_bank_set(bigint,text) to authenticated;

